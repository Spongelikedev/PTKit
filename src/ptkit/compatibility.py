"""Repair legacy assessment values using the unchanged answer topology.

Packet Tracer 4.x saved some DB-backed checks with blank nodeValue fields and
passive-interface checks with interface names. New Packet Tracer versions import
these as explicit values, so even an exact copy of the answer fails the checks.
The encodings below match values regenerated by Packet Tracer 9's Activity Wizard.
No checks, point totals, or reference network settings are changed.
"""
from __future__ import annotations

import re

from .iosconfig import IosConfig
from .model import Network


def repair_legacy_assessment(pt, answer):
    if answer is None:
        return []
    net = Network(answer, pt.doc, 'answer')
    devices = net.devices()
    repairs = []
    major = (pt.version or '').split('.', 1)[0]
    legacy_document = major.isdigit() and int(major) < 5

    def device_for(name):
        matches = [d for d in devices if d.name == name]
        return matches[0] if len(matches) == 1 else None

    def canonical_port(device, port):
        if device is None:
            return port
        names = [p.name for p in device.ports() if p.name]
        if port in names:
            return port
        # PT 4.x called an endpoint's first wired NIC FastEthernet; current
        # versions use FastEthernet0 in the same comparison's value.
        if port and not any(c.isdigit() for c in port) and port + '0' in names:
            return port + '0'
        return port

    for node in pt.root.iterfind('COMPARISONS//NODE'):
        label = node.find('NAME')
        if node.findall('NODE') or label is None or label.get('checkType') != '2':
            continue
        if (label.get('variableName') or label.get('nodeValue') is None
                or label.get('overrideDBGrading') == 'true'):
            continue
        ancestors = [a for a in node.iterancestors() if a.tag == 'NODE'][::-1]
        names = [pt.doc.from_tree(a.findtext('NAME')) or '' for a in ancestors]
        ids = [pt.doc.from_tree(a.findtext('ID')) or '' for a in ancestors]
        ident = pt.doc.from_tree(node.findtext('ID')) or ''
        expected = pt.doc.from_tree(label.get('nodeValue'))
        devs = [d for d in devices if d.name in names or d.name in ids]
        if len(devs) != 1:
            continue
        dev = devs[0]
        replacement = None
        reason = None
        if 'Passive Interface' in ids and 'OSPF' in ids and expected == ident:
            process = next((ids[i] for i in range(len(ids))
                            if names[i].startswith('Process ID ')), None)
            cfg = IosConfig(dev.running_config)
            span = cfg.find_block('router ospf ' + process) if process else None
            if span and any(line.strip() == 'passive-interface ' + ident
                            for line in dev.running_config[span[0]:span[1]]):
                replacement = '1'
                reason = 'Legacy passive-interface entry requires an explicit enabled value.'
        elif (expected == '' and 'Ports' in ids
              and (legacy_document or label.get('variableEnabled') == 'false')):
            idx = ids.index('Ports')
            port = ids[idx + 1] if idx + 1 < len(ids) else None
            link_scope = [value[8:] for value in ids if value.startswith('Link to ')]
            if link_scope and port:
                candidates = []
                for link in net.links():
                    (a_ref, a_port), (b_ref, b_port) = link.endpoints
                    a_dev, b_dev = net.resolve_ref(a_ref), net.resolve_ref(b_ref)
                    if a_dev is not None and b_dev is not None:
                        if a_dev.name == dev.name and a_port == port and b_dev.name == link_scope[0]:
                            candidates.append((link, b_dev, b_port))
                        elif b_dev.name == dev.name and b_port == port and a_dev.name == link_scope[0]:
                            candidates.append((link, a_dev, a_port))
                if len(candidates) == 1:
                    link, remote, remote_port = candidates[0]
                    if ident == 'Type':
                        cable_type = link.el.findtext('CABLE/TYPE')
                        if link.type == 'eSerial':
                            replacement = '2'
                        elif link.type == 'eCopper' and cable_type in ('eStraightThrough', 'eCrossOver'):
                            replacement = '0 ' + ('0' if cable_type == 'eStraightThrough' else '1')
                    elif ident.startswith('Connects to '):
                        replacement = 'Connects to ' + canonical_port(remote, remote_port)
                    reason = 'Legacy link check requires the reference cable/endpoint value.'
            elif port and dev.is_ios:
                cfg = IosConfig(dev.running_config)
                span = cfg.find_block('interface ' + port)
                lines = [line.strip() for line in dev.running_config[span[0]:span[1]]] if span else []
                if ident == 'Encapsulation' and 'encapsulation ppp' in lines:
                    replacement = 'PppProcess'
                    reason = 'Legacy PPP check requires the encapsulation process name.'
                elif ident == 'Native VLAN' and '802.1Q' in ids:
                    values = [m.group(1) for line in lines
                              if (m := re.fullmatch(r'encapsulation dot1[Qq] (\d+) native', line))]
                    if len(values) == 1:
                        replacement = values[0]
                        reason = 'Legacy native VLAN check requires the reference VLAN number.'
        if replacement is not None and replacement != expected:
            label.set('nodeValue', pt.doc.to_tree(replacement))
            # The reference-derived target is now explicit, just as when saved
            # by the current Activity Wizard; preserve every checked criterion.
            label.set('variableEnabled', 'true')
            repairs.append({'path': ' > '.join(names + [label.text or ident]),
                            'previous': expected, 'expected': replacement, 'reason': reason})
    return repairs
